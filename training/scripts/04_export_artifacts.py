#!/usr/bin/env python3
"""导出固件产物：
1. work/best_model.tflite → firmware/tissue_model_data.cc/.h（C 数组）
2. 训练时使用的 40×257 mel 滤波器组 → firmware/tissue_mel_filterbank.cc/.h
   （保证固件前端与训练前端逐位一致）
3. work/model_meta.json（量化参数、前后端参数、阈值建议）
"""
import numpy as np, json, os
from scipy import signal as ss

SR, WIN, HOP, N_MEL, FRAMES = 16000, 512, 160, 40, 64

def mel_bank():
    n_fft = WIN // 2 + 1
    def hz2mel(h): return 2595 * np.log10(1 + h / 700)
    def mel2hz(m): return 700 * (10 ** (m / 2595) - 1)
    m_pts = np.linspace(hz2mel(60), hz2mel(7800), N_MEL + 2)
    h_pts = mel2hz(m_pts)
    bins = np.floor((WIN + 1) * h_pts / SR).astype(int)
    fb = np.zeros((N_MEL, n_fft), dtype=np.float32)
    for i in range(N_MEL):
        a, b_, c = bins[i], bins[i+1], bins[i+2]
        if b_ == a: b_ = a + 1
        if c == b_: c = b_ + 1
        fb[i, a:b_] = np.linspace(0, 1, b_ - a)
        fb[i, b_:c] = np.linspace(1, 0, c - b_)
    return fb

FB = mel_bank()
os.makedirs('firmware', exist_ok=True)

# ---- 模型 C 数组 ----
model_bytes = open('work/best_model.tflite', 'rb').read()
with open('firmware/tissue_model_data.cc', 'w') as f:
    f.write('// Auto-generated by 04_export_artifacts.py — do not edit.\n')
    f.write('#include "tissue_model_data.h"\n\n')
    f.write('alignas(16) const unsigned char g_tissue_model_data[] = {\n')
    for i in range(0, len(model_bytes), 16):
        f.write('  ' + ','.join(str(b) for b in model_bytes[i:i+16]) + ',\n')
    f.write('};\n')
    f.write(f'const unsigned int g_tissue_model_data_len = {len(model_bytes)};\n')
with open('firmware/tissue_model_data.h', 'w') as f:
    f.write('#pragma once\n#include <cstddef>\n#include <cstdint>\n')
    f.write('extern const unsigned char g_tissue_model_data[];\n')
    f.write('extern const unsigned int g_tissue_model_data_len;\n')

# ---- mel 滤波器组 C 数组 ----
with open('firmware/tissue_mel_filterbank.cc', 'w') as f:
    f.write('// Auto-generated — must match training frontend (40 mel, 60-7800Hz, 512 win).\n')
    f.write('#include "tissue_mel_filterbank.h"\n\n')
    f.write('alignas(16) const float g_tissue_mel_filterbank[40 * 257] = {\n')
    flat = FB.reshape(-1)
    def fmt_f(v):
        s = f'{v:.7g}'
        if '.' not in s and 'e' not in s and 'inf' not in s and 'nan' not in s:
            s += '.0'
        return s + 'f'
    for i in range(0, len(flat), 8):
        f.write('  ' + ','.join(fmt_f(v) for v in flat[i:i+8]) + ',\n')
    f.write('};\n')
with open('firmware/tissue_mel_filterbank.h', 'w') as f:
    f.write('#pragma once\n#include <cstdint>\n')
    f.write('#define TISSUE_MEL_BINS 40\n#define TISSUE_FFT_BINS 257\n')
    f.write('#define TISSUE_WIN 512\n#define TISSUE_HOP 160\n#define TISSUE_FRAMES 64\n#define TISSUE_SR 16000\n')
    f.write('extern const float g_tissue_mel_filterbank[40 * 257];\n')

# ---- 元数据 ----
rep = json.load(open('work/threshold_report.json'))
q = rep['quantization']
meta = {
    'model_bytes': len(model_bytes),
    'frontend': {'sample_rate': SR, 'win': WIN, 'hop': HOP, 'n_mel': N_MEL,
                  'frames': FRAMES, 'mel_range_hz': [60, 7800],
                  'norm': 'per-utterance mean/var on log10(power+1e-6)'},
    'quantization': q,
    'input_tensor': 'int8 [1,64,40,1], x_int8 = round(x/scale)+zp, scale=%.6g zp=%d' % (q['in_scale'], q['in_zero_point']),
    'output_tensor': 'int8 scalar, p = (y-zp)*scale, scale=%.6g zp=%d' % (q['out_scale'], q['out_zero_point']),
    'threshold_recommendation': {
        'score_thresh': 0.7,
        'consecutive_windows_required': 3,
        'window_hop_s': 0.5,
        'effective_reaction': '连续约 2 秒抽纸动作后触发（对应"连抽几张"）',
        'refractory_after_trigger_s': 10,
        'note': '正式录音替换合成正样本重训后必须重扫阈值',
    },
}
json.dump(meta, open('work/model_meta.json', 'w'), indent=2, ensure_ascii=False)

# ---- model_meta.h 自动生成（量化参数随模型同步，避免手改） ----
with open('firmware/model_meta.h', 'w') as f:
    f.write('// 由 04_export_artifacts.py 自动生成 —— 与 work/best_model.tflite 配套，勿手改\n')
    f.write('#pragma once\n')
    f.write('#define MODEL_IN_SCALE   %.17gf\n' % q['in_scale'])
    f.write('#define MODEL_IN_ZP      (%d)\n' % q['in_zero_point'])
    f.write('#define MODEL_OUT_SCALE  %.17gf\n' % q['out_scale'])
    f.write('#define MODEL_OUT_ZP     (%d)\n' % q['out_zero_point'])
    f.write('#define MODEL_SCORE_THRESH %.2ff\n' % 0.8)
print('exported: firmware/model_meta.h')

print('exported: firmware/tissue_model_data.{cc,h}, firmware/tissue_mel_filterbank.{cc,h}, work/model_meta.json')
print('model bytes:', len(model_bytes))
